// Write _cm6-LICENSES.txt: the license text of every production dependency
// bundled into the editor scripts, read from the installed packages.
// Build-only tools (rollup and its plugins) are not shipped and not listed.
import fs from 'node:fs/promises';

const here = new URL('./', import.meta.url);
const lock = JSON.parse(await fs.readFile(new URL('package-lock.json', here), 'utf8'));
const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt))?$/i;
// Packages whose npm tarball omits the license their source repository has.
const FALLBACK = {'@uiw/': 'fallback-licenses/uiw-react-codemirror-MIT.txt'};

const sections = [];
for (const [location, entry] of Object.entries(lock.packages)) {
  if (!location || entry.dev) continue;
  const name = location.replace(/^.*node_modules\//, '');
  const folder = new URL(location + '/', here);
  const files = (await fs.readdir(folder)).filter(file => LICENSE_FILE.test(file)).sort();
  const fallback = Object.entries(FALLBACK).find(([prefix]) => name.startsWith(prefix))?.[1];
  const source = files.length ? new URL(files[0], folder) : fallback && new URL(fallback, here);
  if (!source) throw new Error(`${name} ships no license file; add one to FALLBACK.`);
  const text = (await fs.readFile(source, 'utf8')).trim();
  sections.push(`${name} ${entry.version} (${entry.license})\n\n${text}\n`);
}
sections.sort();
const header = 'Third-party software bundled into the AnkiCode editor scripts.\n' +
  'Generated by card-template/editor/notices.mjs from package-lock.json.\n';
await fs.writeFile(new URL('_cm6-LICENSES.txt', here),
  [header, ...sections].join('\n' + '-'.repeat(72) + '\n\n'));
console.log(`Wrote _cm6-LICENSES.txt for ${sections.length} packages.`);
