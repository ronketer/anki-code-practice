"""Turn the same literal Python assertions into a JavaScript test harness."""
import json
import re

from ankicode.test_generator import parse_assertions

MAX_SAFE_INTEGER = 2**53 - 1
_ENTRY = re.compile(r'[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*')


def test_cases(source):
    """Return [arguments, expected] pairs that survive a JSON round trip.

    Raises ValueError for anything parse_assertions rejects, for values JSON
    cannot carry (NaN, sets, bytes) and for integers JavaScript would round.
    """
    cases = [[arguments, expected] for arguments, expected, _ in parse_assertions(source)]
    try:
        json.dumps(cases, allow_nan=False)
    except TypeError as error:
        raise ValueError('test values must be JSON compatible') from error

    def check_integers(value):
        if isinstance(value, int) and not isinstance(value, bool) and abs(value) > MAX_SAFE_INTEGER:
            raise ValueError('integer exceeds JavaScript safe precision')
        if isinstance(value, (list, tuple)):
            for item in value:
                check_integers(item)
        elif isinstance(value, dict):
            for item in value.values():
                check_integers(item)

    check_integers(cases)
    return cases


def harness(cases, entry, mode):
    """Return a JavaScript function body that grades `entry` against `cases`.

    `mode` is a COMPARE_MODES value or None. The body logs PASS/FAIL lines and
    a "passed/total tests passed" summary and returns true when all pass.
    """
    if not _ENTRY.fullmatch(entry):
        raise ValueError('entry point must be a JavaScript name')
    # Data is concatenated, never substituted into the template, so test
    # values can contain any text.
    return ('// Generated by AnkiCode from literal test assertions.\n'
            f'const __cases = {json.dumps(cases, ensure_ascii=True)};\n'
            f'const __mode = {json.dumps(mode)};\n'
            + _HARNESS_BODY.replace('__ENTRY__', entry))


_HARNESS_BODY = '''const __key = x => JSON.stringify(x);
const __outer = (x, deep) => Array.isArray(x) ? x.map(v =>
  deep && Array.isArray(v) ? v.map(__key).sort() : __key(v)).map(__key).sort() : x;
function __equal(actual, expected, args) {
  if (__mode === 'two_sum_0' || __mode === 'two_sum_1') {
    if (expected === null) return actual == null || Array.isArray(actual) && actual.length === 0;
    if (!Array.isArray(actual) || actual.length !== 2 || !actual.every(Number.isInteger)) return false;
    const offset = __mode === 'two_sum_1' ? 1 : 0;
    const [i, j] = actual.map(v => v - offset);
    return i !== j && i >= 0 && j >= 0 && i < args[0].length && j < args[0].length && args[0][i] + args[0][j] === args[1];
  }
  if (__mode === 'outer' || __mode === 'outer_inner')
    return __key(__outer(actual, __mode === 'outer_inner')) === __key(__outer(expected, __mode === 'outer_inner'));
  if (typeof expected === 'number' && !Number.isInteger(expected))
    return typeof actual === 'number' && Math.abs(actual - expected) <= 1e-9 * Math.max(1, Math.abs(expected));
  return __key(actual) === __key(expected);
}
let __passed = 0;
for (let i = 0; i < __cases.length; i++) {
  const [args, expected] = __cases[i];
  try {
    const actual = __ENTRY__(...JSON.parse(JSON.stringify(args)));
    if (__equal(actual, expected, args)) { __passed++; console.log('PASS ' + (i + 1)); }
    else console.log('FAIL ' + (i + 1) + ': input=' + __key(args) + ' expected=' + __key(expected) + ' got=' + __key(actual));
  } catch (error) { console.log('FAIL ' + (i + 1) + ': ' + String(error)); }
}
console.log(__passed + '/' + __cases.length + ' tests passed');
return __passed === __cases.length;
'''
